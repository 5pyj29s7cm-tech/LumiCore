export function topTools(steps: WorkflowStep[]): { name: string; count: number }[] {
  const counts: Record<string, number> = {};
  for (const s of steps) {
    counts[s.name] = (counts[s.name] || 0) + 1;
  }
  return Object.entries(counts)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 5)
    .map(([name, count]) => ({ name, count }));
}

export function buildHandlerFunction(handlerCode: string, inputSchema: any): string {
  const props = inputSchema?.properties || {};
  const paramNames = Object.keys(props);

  const destructure = paramNames.length > 0
    ? `  const { ${paramNames.join(', ')} } = args;`
    : '  // No parameters defined';

  // Indent the LLM-generated body code to match the function body
  const sanitizedBody = sanitizeHandlerBody(handlerCode, paramNames);

  const indentedBody = sanitizedBody
    .split('\n')
    .map(line => line.trim() ? `  ${line}` : '')
    .join('\n');

  return `async (args: Record<string, any>): Promise<{ content: Array<{ type: 'text'; text: string }> }> => {
${destructure}
  let result = '';

  // ── Generated implementation ──
${indentedBody}

  result = JSON.stringify({ status: 'completed', data: JSON.parse(result) });

  return {
    content: [{ type: 'text', text: result }],
  };
}`;
}

export function sanitizeHandlerBody(handlerCode: string, paramNames: string[]): string {
  const duplicateDestructure = paramNames.length
    ? new RegExp(`^\\s*const\\s*\\{\\s*${paramNames.map(escapeRegExp).join('\\s*,\\s*')}\\s*\\}\\s*=\\s*args\\s*;\\s*$`)
    : null;

  return String(handlerCode || '')
    .replace(/^```(?:ts|typescript|js|javascript)?\s*/i, '')
    .replace(/```\s*$/i, '')
    .split('\n')
    .filter(line => !duplicateDestructure?.test(line))
    .join('\n')
    .trim();
}

export function buildSchemaLiteral(schema: any): string {
  if (!schema || !schema.properties) {
    return 'z.object({})';
  }

  const props = schema.properties || {};

  const propEntries = Object.entries(props).map(([key, prop]: [string, any]) => {
    return `  ${JSON.stringify(key)}: ${mapJsonTypeToZod(prop)}${prop.description ? `.describe('${escapeTsSingleQuoted(prop.description)}')` : ''}`;
  });

  if (propEntries.length === 0) {
    return `z.object({})`;
  }

  return `z.object({\n${propEntries.join(',\n')}\n})`;
}

export function mapJsonTypeToZod(prop: any): string {
  const jsonType = prop?.type || 'string';
  switch (jsonType) {
    case 'string': return 'z.string()';
    case 'number': return 'z.number()';
    case 'integer': return 'z.number()';
    case 'boolean': return 'z.boolean()';
    case 'array': return 'z.array(z.any())';
    case 'object': return 'z.record(z.any())';
    default: return 'z.string()';
  }
}

export function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

export function escapeTsSingleQuoted(value: string): string {
  return String(value || '').replace(/\\/g, '\\\\').replace(/'/g, "\\'")
    .replace(/\r/g, '\\r').replace(/\n/g, '\\n').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

export function escapeJsonString(value: string): string {
  return JSON.stringify(String(value || '')).slice(1, -1);
}
