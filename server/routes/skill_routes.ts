import { Router, Request, Response, NextFunction } from "express";
import path from "path";
import fs from "fs";
import os from "os";
import { execFileSync } from "child_process";
import { readDB, writeDB } from "../../db_layer";
import { mcpManager, getMCPConfig, updateMCPConfig, SKILLS_DIR, normalizeSkillInstallName } from "../mcp";
import { generateSkill } from "../skills/generator";
import { getRecentWorkflows } from "../skills/worklog";
import { getDataPath } from "../config/data_path";
import { loadKeys } from "../config/keys";
import { requireAuth } from "../middleware/auth";
import { createAgentForSkill } from "../agents/skill_agent";

const asyncHandler = (fn: (req: Request, res: Response, next?: NextFunction) => Promise<any>) =>
  (req: Request, res: Response, next: NextFunction) =>
    Promise.resolve(fn(req, res, next)).catch(next);

function getStartupFailureNote(description: string | undefined): string | undefined {
  const match = String(description || '').match(/\(disabled after startup failure:\s*([^)]+)\)\s*$/i);
  return match?.[1]?.trim();
}

function stripStartupFailureNote(description: string | undefined, fallback: string): string {
  return String(description || fallback).replace(/\s*\(disabled after startup failure:[^)]+\)\s*$/i, '').trim();
}

export function mountSkillRoutes(
  router: Router,
  jwtSecret: string,
  llmGetters: {
    getDeepSeek: () => any;
    getGemini: () => any;
    getOpenAI?: () => any;
    getAnthropic?: () => any;
    getQwen?: () => any;
  },
  io: { emit: (event: string, data: any) => void },
) {
  const removeAutoAgentForSkill = (name: string) => {
    const agentId = `skill_${name.toLowerCase().replace(/[^a-z0-9]/g, '-')}`;
    try {
      const db = readDB();
      if (db.agents) {
        const idx = db.agents.findIndex((a: any) => a.id === agentId && a.autoCreated);
        if (idx !== -1) {
          db.agents.splice(idx, 1);
          writeDB(db);
          io.emit('agent:removed', { id: agentId });
        }
      }
    } catch {}
  };

  // List all installed skills (local + external MCP servers)
  router.get("/skills", (req, res) => {
    try {
      const localSkills = mcpManager.listLocalSkills();
      const mcpConfig = getMCPConfig();
      const health = mcpManager.getServerHealth();
      const allSkills = Object.entries(mcpConfig).map(([name, config]) => {
        const local = localSkills.find(s => s.name === name);
        const serverHealth = health[name];
        const startupError = serverHealth?.lastError || getStartupFailureNote(config.description);
        return {
          name,
          description: stripStartupFailureNote(config.description, name),
          enabled: config.enabled,
          source: config.source || 'external',
          autoGenerated: config.autoGenerated || false,
          generatedFrom: config.generatedFrom,
          toolCount: config.toolCount || (local?.toolCount || 0),
          installedAt: local?.installedAt || '',
          connected: mcpManager.getConnectedServers().includes(name),
          broken: local?.broken || false,
          healthStatus: serverHealth?.status || 'unknown',
          startupError,
          consecutiveCrashes: serverHealth?.consecutiveCrashes || 0,
          lastCrashTime: serverHealth?.lastCrashTime,
          lastSuccessfulConnect: serverHealth?.lastSuccessfulConnect,
          requiresApiKey: config.requiresApiKey || false,
          apiKeyEnv: config.apiKeyEnv,
          apiKeyUrl: config.apiKeyUrl,
        };
      });
      res.json({ skills: allSkills });
    } catch (err: any) {
      res.status(500).json({ error: err.message });
    }
  });

  // Generate a skill from description or workflows
  router.post("/skills/generate", asyncHandler(async (req, res) => {
    try {
      const { description, provider, model } = req.body;

      let workflows;
      if (req.body.workflowIds) {
        const allWorkflows = getRecentWorkflows();
        workflows = allWorkflows.filter(w => (req.body.workflowIds as string[]).includes(w.id));
      } else if (req.body.useRecent) {
        workflows = getRecentWorkflows().slice(-5);
      }

      const result = await generateSkill(
        {
          description,
          workflows,
          provider: provider || 'deepseek',
          model: model || 'deepseek-chat',
          userId: (req as any).user?.uid || 'anonymous',
        },
        llmGetters.getDeepSeek, llmGetters.getGemini, llmGetters.getOpenAI, llmGetters.getAnthropic, llmGetters.getQwen,
      );

      if (result.success) {
        // Save generated skill code to knowledge base for agent ingestion
        try {
          const kbDir = getDataPath('knowledge');
          fs.mkdirSync(kbDir, { recursive: true });
          const safeName = `skill-${result.skillName}.ts`;
          fs.writeFileSync(path.join(kbDir, safeName), result.generatedCode || '', 'utf-8');
          const db = readDB();
          if (!db.knowledgeFiles) db.knowledgeFiles = [];
          const existing = db.knowledgeFiles.find((m: any) => m.filename === safeName);
          if (existing) {
            existing.source = 'generated';
            existing.updatedAt = new Date().toISOString();
          } else {
            db.knowledgeFiles.push({
              filename: safeName,
              source: 'generated',
              agentIds: [],
              createdAt: new Date().toISOString(),
              updatedAt: new Date().toISOString(),
            });
          }
          writeDB(db);
        } catch (e) {
          console.warn('[SkillGen] Failed to save to knowledge base:', e);
        }
        io.emit('skill:updated', { name: result.skillName });
        createAgentForSkill(result.skillName, {
          description: description || 'Auto-generated skill',
          category: 'general',
          installSource: 'generated',
        }, io);
        res.json(result);
      } else {
        res.status(400).json(result);
      }
    } catch (err: any) {
      res.status(500).json({ error: err.message });
    }
  }));

  // Install a skill from git/npm/local
  router.post("/skills/install", async (req, res) => {
    try {
      const { source, url, package: pkgName, path: localPath, name } = req.body;

      if (source === 'git' && url) {
        const skillName = normalizeSkillInstallName(name || url.split('/').pop()?.replace('.git', '') || 'unnamed');
        const tmpDir = path.join(os.tmpdir(), `lumi_skill_${Date.now()}`);
        let destDir = '';
        try {
          execFileSync('git', ['clone', String(url), tmpDir], { stdio: 'pipe', timeout: 30000, windowsHide: true });
          destDir = mcpManager.installSkill(skillName, tmpDir);
        } finally {
          fs.rmSync(tmpDir, { recursive: true, force: true });
        }

        // Restart to pick up new skill
        await mcpManager.restartServer(skillName);
        createAgentForSkill(skillName, { description: `Git install: ${url}`, category: 'general', installSource: 'git' }, io);
        res.json({ success: true, name: skillName, directory: destDir });
      } else if (source === 'local' && localPath) {
        const skillName = normalizeSkillInstallName(name || path.basename(localPath));
        const destDir = mcpManager.installSkill(skillName, localPath);
        await mcpManager.restartServer(skillName);
        createAgentForSkill(skillName, { description: `Local install: ${localPath}`, category: 'general', installSource: 'local' }, io);
        res.json({ success: true, name: skillName, directory: destDir });
      } else if (source === 'npm' && pkgName) {
        const npmDir = await mcpManager.installFromNpm(pkgName);
        const npmName = path.basename(npmDir);
        await mcpManager.restartServer(npmName);
        io.emit('skill:installed', { name: npmName, source: 'npm' });
        createAgentForSkill(npmName, { description: `npm package: ${pkgName}`, category: 'general', installSource: 'npm' }, io);
        res.json({ success: true, name: npmName, directory: npmDir });
      } else if (source === 'github' && url) {
        const ghDir = await mcpManager.installFromGitHub(url);
        const ghName = path.basename(ghDir);
        await mcpManager.restartServer(ghName);
        io.emit('skill:installed', { name: ghName, source: 'github' });
        createAgentForSkill(ghName, { description: `GitHub repo: ${url}`, category: 'general', installSource: 'github' }, io);
        res.json({ success: true, name: ghName, directory: ghDir });
      } else {
        res.status(400).json({ error: 'Invalid source. Use: git (with url), local (with path), or npm (with package)' });
      }
    } catch (err: any) {
      res.status(500).json({ error: err.message });
    }
  });

  // Repair a local skill by reinstalling known sources or restarting it
  router.post("/skills/:name/repair", async (req, res) => {
    try {
      const result = await mcpManager.repairSkill(req.params.name);
      if (!result.success) return res.status(400).json(result);
      io.emit('skill:updated', { name: req.params.name });
      res.json(result);
    } catch (err: any) {
      res.status(500).json({ success: false, error: err.message });
    }
  });

  // Explicitly clean incomplete local skills
  router.delete("/skills/broken", async (_req, res) => {
    try {
      const removed = mcpManager.cleanupBrokenSkills();
      for (const name of removed) {
        io.emit('skill:uninstalled', { name });
        removeAutoAgentForSkill(name);
      }
      res.json({ success: true, removed });
    } catch (err: any) {
      res.status(500).json({ error: err.message });
    }
  });

  // Uninstall a skill
  router.delete("/skills/:name", async (req, res) => {
    try {
      mcpManager.uninstallSkill(req.params.name);
      io.emit('skill:uninstalled', { name: req.params.name });
      removeAutoAgentForSkill(req.params.name);
      res.json({ success: true });
    } catch (err: any) {
      res.status(500).json({ error: err.message });
    }
  });

  // Enable a skill
  router.post("/skills/:name/enable", async (req, res) => {
    try {
      const config = getMCPConfig();
      if (!config[req.params.name]) return res.status(404).json({ error: 'Skill not found' });
      const skillConfig = config[req.params.name];
      if (skillConfig.requiresApiKey && skillConfig.apiKeyEnv) {
        const stored = loadKeys()[skillConfig.apiKeyEnv]?.trim();
        const fromEnv = process.env[skillConfig.apiKeyEnv]?.trim();
        if (!stored && !fromEnv) {
          return res.status(400).json({
            error: `Configure ${skillConfig.apiKeyEnv} before enabling this skill.`,
            requiresApiKey: true,
            apiKeyEnv: skillConfig.apiKeyEnv,
            apiKeyUrl: skillConfig.apiKeyUrl,
          });
        }
      }
      skillConfig.enabled = true;
      updateMCPConfig(config);
      try { await mcpManager.restartServer(req.params.name); } catch {} // start the process
      res.json({ success: true });
    } catch (err: any) {
      res.status(500).json({ error: err.message });
    }
  });

  // Disable a skill
  router.post("/skills/:name/disable", async (req, res) => {
    try {
      const config = getMCPConfig();
      if (!config[req.params.name]) return res.status(404).json({ error: 'Skill not found' });
      config[req.params.name].enabled = false;
      updateMCPConfig(config);
      try { await mcpManager.disconnectServer(req.params.name); } catch {} // stop the process
      res.json({ success: true });
    } catch (err: any) {
      res.status(500).json({ error: err.message });
    }
  });

  // Workflow inspection (for debugging / manual generation)
  router.get("/skills/workflows", (req, res) => {
    const workflows = getRecentWorkflows((req as any).user?.uid);
    res.json({ workflows: workflows.slice(-20), total: workflows.length });
  });
}
