it('keeps an open skill detail synchronized with toggles, refreshed data and external removal', async () => {
  let skills = [{ name: 'ledger', description: 'original description', enabled: true, connected: true, source: 'local', autoGenerated: false, toolCount: 1 }];
  skillApi.mockImplementation(async (url: string, options?: RequestInit) => {
    if (options?.method === 'POST') skills = skills.map(skill => ({ ...skill, enabled: url.endsWith('/enable') }));
    return { ok: true, json: async () => url === '/api/skills' ? { skills } : url === '/api/explore/profession' ? { profiles: [] } : [] };
  });
  render(<SkillCenter t={{}} lang="en" initialTab="installed" />);
  fireEvent.click(await screen.findByRole('heading', { name: 'ledger' }));
  const detail = within(screen.getByRole('button', { name: 'Close' }).parentElement!);
  fireEvent.click(detail.getByRole('button', { name: 'Disable' }));
  fireEvent.click(await detail.findByRole('button', { name: 'Enable' }));
  await detail.findByRole('button', { name: 'Disable' });
  expect(skillApi).toHaveBeenCalledWith('/api/skills/ledger/disable', { method: 'POST' });
  expect(skillApi).toHaveBeenCalledWith('/api/skills/ledger/enable', { method: 'POST' });
  skills = skills.map(skill => ({ ...skill, description: 'fresh description' }));
  await act(async () => { skillEvents.get('skill:updated')?.forEach(fn => fn()); });
  expect(detail.getByText('fresh description')).toBeTruthy();
  skills = [];
  await act(async () => { skillEvents.get('skill:uninstalled')?.forEach(fn => fn()); });
  await waitFor(() => expect(screen.queryByRole('button', { name: 'Close' })).toBeNull());
  skills = [{ name: 'ledger', description: 'reinstalled', enabled: true, connected: true, source: 'local', autoGenerated: false, toolCount: 1 }];
  await act(async () => { skillEvents.get('skill:installed')?.forEach(fn => fn()); });
  expect(screen.queryByRole('button', { name: 'Close' })).toBeNull();
  expect(screen.getByRole('heading', { name: 'ledger' })).toBeTruthy();
});

it('isolates attachment sessions, carries initial uploads, and releases close listeners on unmount', () => {
  const reset = vi.fn();
  const { result, unmount } = renderHook(() => useConversationAttachments('synthetic:personal', reset));
  const other = renderHook(() => useConversationAttachments('synthetic:organization', reset));
  const file = createChatAttachmentReference({ fileId: 'sample.txt', fileName: 'sample.txt', path: 'C:/synthetic/sample.txt', content: 'private material' });
  act(() => result.current.rememberConversationAttachments([file]));
  act(() => result.current.bindAttachmentContextToConversation('a', { carryCurrent: true }));
  expect(result.current.conversationAttachments).toEqual([file]);
  expect(localStorage.getItem('synthetic:personal:a')).not.toContain('private material');
  act(() => other.result.current.bindAttachmentContextToConversation('a'));
  expect(other.result.current.conversationAttachments).toEqual([]);
  act(() => result.current.bindAttachmentContextToConversation('b'));
  expect(result.current.conversationAttachments).toEqual([]);
  act(() => result.current.bindAttachmentContextToConversation('a'));
  expect(result.current.conversationAttachments.map(item => item.fileId)).toEqual(['sample.txt']);
  const close = (conversationId: string) => window.dispatchEvent(new CustomEvent('lumi:conversation-closed', { detail: { conversationId } }));
  act(() => close('b'));
  expect(result.current.attachmentConversationIdRef.current).toBe('a');
  act(() => close('a'));
  expect(result.current.attachmentConversationIdRef.current).toBe('');
  expect(result.current.conversationAttachments).toEqual([]);
  expect(localStorage.getItem('synthetic:personal:a')).toBeNull();
  unmount(); other.unmount(); reset.mockClear();
  act(() => close('a'));
  expect(reset).not.toHaveBeenCalled();
});

