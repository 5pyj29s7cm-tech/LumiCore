it('refreshes after confirmed install and uninstall, while a rejected deletion keeps the skill', async () => {
  let installed = false, rejectDelete = true;
  const row = { ...marketRow('test-skill'), installSource: 'bundled', officialIdentityStatus: 'verified', enabled: true, connected: true, usable: true, source: 'local', toolCount: 1 };
  vi.spyOn(window, 'confirm').mockReturnValue(true);
  skillApi.mockImplementation(async (url: string, init?: RequestInit) => {
    if (url.endsWith('/acquire')) { installed = true; return skillReply({ success: true }); }
    if (init?.method === 'DELETE') { if (rejectDelete) return { ...skillReply({ error: 'denied' }), ok: false }; installed = false; return skillReply({ success: true }); }
    if (url === '/api/skills') return skillReply({ skills: installed ? [row] : [] });
    return url.includes('/marketplace/skills?') ? skillReply([{ ...row, installed }]) : emptySkillReply(url);
  });
  const view = render(<SkillCenter t={{}} lang="en" initialTab="marketplace" />);
  fireEvent.click(await screen.findByRole('button', { name: 'Install' }));
  expect((await screen.findByRole('button', { name: 'Installed' }) as HTMLButtonElement).disabled).toBe(true);
  view.rerender(<SkillCenter t={{}} lang="en" initialTab="installed" />);
  fireEvent.click(await screen.findByTitle('Uninstall'));
  await waitFor(() => expect(skillApi).toHaveBeenCalledWith('/api/skills/test-skill', { method: 'DELETE' }));
  await waitFor(() => expect(screen.getByRole('heading', { name: 'test-skill' })).toBeTruthy());
  rejectDelete = false;
  fireEvent.click(screen.getByTitle('Uninstall'));
  await screen.findByText('No skills installed');
  expect(window.confirm).toHaveBeenCalledTimes(1);
});

