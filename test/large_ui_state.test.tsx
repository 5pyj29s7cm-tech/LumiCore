function pendingSkillReply() {
  let resolve!: (value: any) => void, reject!: (error: Error) => void;
  const promise = new Promise<any>((ok, fail) => { resolve = ok; reject = fail; });
  return { promise, resolve, reject };
}
const skillReply = (data: any) => ({ ok: true, json: async () => data });
const emptySkillReply = (url: string) => skillReply(url === '/api/skills' ? { skills: [] } : url === '/api/explore/profession' ? { profiles: [] } : []);
const marketRow = (name: string) => ({ id: name, name, description: name, author: 'test', downloads: 0, rating: 0, category: 'test', icon: 'Wrench', installed: false });

it('discards a late previous-language catalog without reloading unrelated skill data', async () => {
  const old = pendingSkillReply();
  skillApi.mockImplementation((url: string) => url === '/api/marketplace/skills?lang=en' ? old.promise
    : Promise.resolve(url === '/api/marketplace/skills?lang=zh' ? skillReply([marketRow('current catalog')]) : emptySkillReply(url)));
  const view = render(<SkillCenter t={{}} lang="en" initialTab="marketplace" />);
  await waitFor(() => expect(skillApi.mock.calls.filter(([url]) => url === '/api/skills')).toHaveLength(1));
  const previousRefresh = [...skillEvents.get('skill:updated')!][0];
  view.rerender(<SkillCenter t={{}} lang="zh" initialTab="marketplace" />);
  await screen.findByRole('heading', { name: 'current catalog' });
  await act(async () => { old.resolve(skillReply([marketRow('stale catalog')])); });
  expect(screen.queryByRole('heading', { name: 'stale catalog' })).toBeNull();
  expect(skillApi.mock.calls.filter(([url]) => url === '/api/skills')).toHaveLength(1);
  expect(skillApi.mock.calls.filter(([url]) => url === '/api/explore/profession')).toHaveLength(1);
  const localizedReads = () => skillApi.mock.calls.filter(([url]) => url === '/api/marketplace/skills?lang=zh').length;
  const beforeLateRefresh = localizedReads();
  await act(async () => { previousRefresh(); });
  expect(localizedReads()).toBe(beforeLateRefresh + 1);
});

it('coalesces same-tick skill events and keeps the newest installed result when an older read fails', async () => {
  const reads: ReturnType<typeof pendingSkillReply>[] = [];
  skillApi.mockImplementation((url: string) => { if (url !== '/api/skills') return Promise.resolve(emptySkillReply(url)); const next = pendingSkillReply(); reads.push(next); return next.promise; });
  render(<SkillCenter t={{}} lang="en" initialTab="installed" />);
  await waitFor(() => expect(reads).toHaveLength(1));
  await act(async () => { fireEvent.click(screen.getByTitle('Refresh')); for (const event of ['skill:updated', 'skill:uninstalled', 'mcp:health_update']) skillEvents.get(event)?.forEach(fn => fn()); });
  expect(reads).toHaveLength(2);
  await act(async () => { reads[1].resolve(skillReply({ skills: [{ name: 'current installed', description: '', enabled: true, connected: true, source: 'local', toolCount: 1 }] })); });
  await screen.findByRole('heading', { name: 'current installed' });
  await act(async () => { reads[0].reject(Error('stale installed failure')); });
  expect(screen.queryByText(/stale installed failure/)).toBeNull();
  expect(screen.getByRole('heading', { name: 'current installed' })).toBeTruthy();
});

it('invalidates search results immediately, keeps partial success, and aborts work on unmount', async () => {
  const reads = new Map<string, { reply: ReturnType<typeof pendingSkillReply>; signal?: AbortSignal | null }>();
  skillApi.mockImplementation((url: string, init?: RequestInit) => {
    if (!url.includes('/discover/')) return Promise.resolve(emptySkillReply(url));
    const reply = pendingSkillReply(); reads.set(url, { reply, signal: init?.signal }); return reply.promise;
  });
  const view = render(<SkillCenter t={{}} lang="en" initialTab="marketplace" />);
  const search = screen.getByPlaceholderText('Search skills...');
  fireEvent.change(search, { target: { value: 'old' } });
  await waitFor(() => expect(reads.size).toBe(2));
  fireEvent.change(search, { target: { value: 'new' } });
  await waitFor(() => expect(reads.size).toBe(4));
  await act(async () => {
    reads.get('/api/marketplace/discover/npm?q=new')!.reply.resolve(skillReply({ results: [{ id: 'new', name: 'current npm' }] }));
    reads.get('/api/marketplace/discover/github?topic=new')!.reply.reject(Error('current GitHub failure'));
  });
  await screen.findByText('current npm');
  expect(screen.getByText('current GitHub failure')).toBeTruthy();
  await act(async () => { for (const [url, read] of reads) if (url.endsWith('old')) read.reply.reject(Error('stale search failure')); });
  expect(screen.queryByText(/stale search failure/)).toBeNull();
  fireEvent.change(search, { target: { value: '' } });
  expect(screen.queryByText('current npm')).toBeNull();
  expect(screen.queryByText('current GitHub failure')).toBeNull();
  fireEvent.change(search, { target: { value: 'pending' } });
  await waitFor(() => expect(reads.size).toBe(6));
  const staleRefresh = [...skillEvents.get('skill:updated')!][0], callsBeforeClose = skillApi.mock.calls.length;
  view.unmount();
  await act(async () => { staleRefresh(); });
  expect(skillApi).toHaveBeenCalledTimes(callsBeforeClose);
  for (const read of reads.values()) expect(read.signal?.aborted).toBe(true);
});

